"""
match_from_cst.py (step 8): matching network recomputed on a CST impedance.

- the Touchstone reading recovers a known Z (50 Ohm and 1 Ohm references, "R 0" + forced reference);
- the MoM / CST frequency offset is recovered on a synthetic shifted impedance;
- with the MoM Z_in of the design written as a .s1p, the script finds the step-6b result
  (skipped when the step-6b files are not on this machine).
"""

import importlib.util
import json
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location(
    "match_from_cst", ROOT / "solver/antenna_simulation/euraap_challenge/match_from_cst.py")
mfc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mfc)
mt = mfc.mt


def z_known(f_hz):
    """B3-like impedance: R ~ 27 Ohm, steep X (series RLC with an offset)."""
    w, w0 = 2 * np.pi * f_hz, 2 * np.pi * 1e9
    return 26.0 + 2.0 * (f_hz / 1e9 - 1) + 1j * (300.0 + 30.0 * (w / w0 - w0 / w) / 0.01)


def write_s1p(path, f_hz, z, r_port=50.0, r_written=None, fmt="MA", unit="GHz"):
    s = (z - r_port) / (z + r_port)
    scale = {"GHz": 1e9, "MHz": 1e6, "Hz": 1.0}[unit]
    r_written = r_port if r_written is None else r_written
    lines = ["! TOUCHSTONE file generated by CST MICROWAVE STUDIO", "! test file",
             f"# {unit} S {fmt} R {r_written:g}"]
    for f, x in zip(f_hz, s):
        a, b = (abs(x), np.degrees(np.angle(x))) if fmt == "MA" else (x.real, x.imag)
        lines.append(f"{f / scale:<22.15g} {a:.16g} {b:.16g}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


@pytest.mark.parametrize("r_port, fmt, unit", [(50.0, "MA", "GHz"), (1.0, "RI", "MHz")])
def test_s1p_recovers_known_impedance(tmp_path, r_port, fmt, unit):
    f = np.linspace(0.95e9, 1.05e9, 101)
    p = tmp_path / "a.s1p"
    write_s1p(p, f, z_known(f), r_port=r_port, fmt=fmt, unit=unit)
    d = mfc.read_s1p(p)
    assert d["z_ref_file"] == r_port and d["z_ref_used"] == r_port
    np.testing.assert_allclose(d["f_hz"], f, rtol=1e-14)
    np.testing.assert_allclose(d["z"], z_known(f), rtol=1e-9)


def test_s1p_r0_needs_forced_reference(tmp_path):
    f = np.linspace(0.95e9, 1.05e9, 21)
    p = tmp_path / "r0.s1p"
    write_s1p(p, f, z_known(f), r_port=1.0, r_written=0.0)        # CST "R 0": S relative to a 1 Ohm port
    with pytest.raises(ValueError, match="R 0"):
        mfc.read_s1p(p)
    d = mfc.read_s1p(p, z_ref=1.0)
    assert d["z_ref_file"] == 0.0 and d["z_ref_used"] == 1.0
    np.testing.assert_allclose(d["z"], z_known(f), rtol=1e-9)


@pytest.mark.parametrize("s_true", [0.008, -0.005])
def test_frequency_shift_recovered(s_true):
    f0 = 1e9
    fm = np.linspace(0.98e9, 1.02e9, 41)
    mom = mt.AntennaOnePort(fm, z_known(fm), np.full(fm.shape, 9.0), f0)
    fc = np.linspace(0.95e9, 1.05e9, 1001)
    z_cst = z_known(fc * (1 + s_true))                               # X_CST(f) = X_MoM(f (1 + s))
    sh = mfc.estimate_frequency_shift(fc, z_cst, mom, f0)
    assert abs(sh["s"] - s_true) < 2e-5
    assert abs(sh["s_at_f0"] - s_true) < 2e-5
    ant, ant_z, info = mfc.build_antennas(fc, z_cst, f0, mom=mom)
    assert abs(ant.f_max - 1.02e9 / (1 + s_true)) <= 1e5 + 1e-9 * f0   # G_A known only where shifted MoM data exist


def _write_cut(path, f_ghz, g_phi_plus_y):
    """CST-like far-field cut theta = 90 deg (phi 0..359, 1 deg) with Abs(Phi) = g at phi = 90 deg."""
    lines = ["#Parameters = {X=76.25}", f"farfield (f={f_ghz:g}) (X=76.25)",
             "Theta [deg.]  Phi   [deg.]  Abs(Gain)[dBi   ]   Abs(Theta)[dBi   ]  Phase(Theta)[deg.]  "
             "Abs(Phi  )[dBi   ]  Phase(Phi  )[deg.]  Ax.Ratio[dB    ]    ", "-" * 150, ""]
    for phi in range(360):
        gp = g_phi_plus_y if phi == 90 else -5.0 - abs(phi - 90) / 30
        lines.append(f"  90.000  {phi:10.3f}  {gp + 0.001:12.4e}  {-50.0:12.4e}  {0.0:10.3f}  {gp:12.4e}  {0.0:10.3f}  {40.0:12.4e}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def test_gain_csv_from_cuts(tmp_path):
    for f, g in ((0.99, 9.23), (1.0, 9.38), (1.01, 9.27)):
        _write_cut(tmp_path / f"farfield_cut_theta=90_f={f:g}GHz.txt", f, g)
    out, rows = mfc.gain_csv_from_cuts(tmp_path, tmp_path / "g.csv")
    assert [r[0] for r in rows] == [0.99, 1.0, 1.01] and [r[1] for r in rows] == [9.23, 9.38, 9.27]
    f, g = mfc.read_gain_csv(out)
    np.testing.assert_allclose(f, [0.99e9, 1.0e9, 1.01e9])
    np.testing.assert_allclose(10 * np.log10(g), [9.23, 9.38, 9.27], atol=1e-4)


def test_bench_tuning_part_changes():
    caps = {p.label: p for p in mt.electrical_parts(mfc.CAPACITOR_KITS) if p.alternatives[0].size == "0603"}
    ref = mt.Network("c_sp", (caps["2.7 pF"], caps["1.2 pF"], caps["1 pF"]))
    swapped = mt.Network("c_sp", (caps["2.7 pF"], caps["1 pF"], caps["1.2 pF"]))   # series parts commute
    assert mfc.part_changes(ref, swapped) == []
    one = mt.Network("c_sp", (caps["2.7 pF"], caps["1.5 pF"], caps["1.2 pF"]))
    assert mfc.part_changes(ref, one) == [{"position": "series", "from": "1 pF", "to": "1.5 pF"}]


@pytest.mark.skipif(not (mfc.MOM_FREQ_CSV.is_file() and mfc.REF_6B_JSON.is_file()),
                    reason="step-6b MoM table / matching JSON not available")
def test_mom_impedance_as_s1p_reproduces_step_6b(tmp_path):
    f0 = 1e9
    mom = mfc.load_mom_oneport(mfc.MOM_FREQ_CSV, f0)
    s1p = tmp_path / "V6mom" / "mom.s1p"
    s1p.parent.mkdir()
    write_s1p(s1p, mom.f_hz, mom.zin_data)
    doc = mfc.run(s1p, "V6mom", out_dir=tmp_path / "out", f0=f0, esl_rankings=False, figure=False,
                  log=lambda *a: None)
    ref = json.loads(mfc.REF_6B_JSON.read_text(encoding="utf-8"))
    assert abs(doc["gain"]["shift"]["s"]) < 1e-6
    best6 = ref["solutions"][0]
    mine = doc["solutions"][0]
    assert mfc.network_from_record(mine).key() == mfc.network_from_record(best6).key()
    for k in ("G_r_nominal_dBi", "G_r_mean_dBi", "G_r_p10_dBi", "S11_dB"):
        assert abs(mine["expected"][k] - best6["expected"][k]) < 1e-3, k
    assert abs(mine["expected"]["band"]["bw_MHz"] - best6["expected"]["band"]["bw_MHz"]) < 0.1
    assert doc["comparison_6b"]["same_components_as_best"] is True
    # same top-10 ranking (electrically equivalent networks)
    keys6 = [mfc.network_from_record(s).key() for s in ref["solutions"]]
    keys = [mfc.network_from_record(s).key() for s in doc["solutions"]]
    assert keys == keys6
    assert (tmp_path / "out" / "adaptation_from_cst.json").is_file()
