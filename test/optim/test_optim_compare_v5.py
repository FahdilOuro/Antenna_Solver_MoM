def _csv_text(rows):
    keys = list(rows[0])
    fmt = lambda v: f"{v:.12g}" if isinstance(v, (float, np.floating)) else str(v)   # noqa: E731
    return ",".join(keys) + "\n" + "\n".join(",".join(fmt(r[k]) for k in keys) for r in rows) + "\n"


def _write_case(d, rows, meta, pattern=None, extra=None):
    d.mkdir(parents=True)
    if rows:
        (d / "results.csv").write_text(_csv_text(rows), encoding="utf-8")
    for name, r in (extra or {}).items():
        (d / name).write_text(_csv_text(r), encoding="utf-8")
    if pattern:
        pk = list(pattern[0])
        (d / "pattern_xy.csv").write_text(
            ",".join(pk) + "\n" + "\n".join(",".join(f"{r[k]:.12g}" for k in pk) for r in pattern) + "\n",
            encoding="utf-8")
    (d / "metadata.json").write_text(json.dumps(dict(meta, case=d.name, complete=True)),
                                     encoding="utf-8")


def test_readers_recover_known_impedances(fake_tree):
    cst = cmp.load_cst(fake_tree["cst"])
    f, z = cst["V5a"]["zin"]                                     # s1p, MHz, RI
    np.testing.assert_allclose(f, fake_tree["f_a"], rtol=1e-12)
    np.testing.assert_allclose(z, z_dipole(f), rtol=1e-9)
    fm, zm = cst["V5a"]["zin_mag"]                               # |Zin| txt, MHz, junk line
    assert len(fm) == len(fake_tree["f_a"])
    np.testing.assert_allclose(fm, fake_tree["f_a"], rtol=1e-9)
    np.testing.assert_allclose(zm, np.abs(z_dipole(fm)), rtol=1e-9)

    cut = cst["V5a"]["cut"]
    assert {"Theta", "Phi", "Abs(Dir.)", "Abs(Phi)", "Ax.Ratio"} <= set(cut)
    assert len(cut["Phi"]) == 360

    for (mat, w), r_loss in ((("pec", 2.0), 0.0), (("cu", 2.0), 0.4)):
        f, z = cst["V5b"][(mat, w)]["zin"]                       # MA and DB formats
        np.testing.assert_allclose(z, z_loop(f, r_loss), rtol=1e-9)

    # Re/Im text file is read as complex
    f, z = cmp.read_cst_zin(fake_tree["cst"] / "V5b" / "copper_w=2" / "Zin.txt")
    assert np.iscomplexobj(z)
    np.testing.assert_allclose(z, z_loop(f, 0.4), rtol=1e-9)

    eta, label = cmp._cst_eta(cst, 2.0)
    assert "Re Z_PEC" in label
    assert abs(eta - 0.9 / 1.3) < 1e-9

    # V5b' kept apart from V5b; "R 0" file read with the imposed 1 Ohm reference
    assert set(cst["V5bp"]) == {("cu", 2.0), ("pec", 2.0)} and ("cu", 2.0) in cst["V5b"]
    f, z = cst["V5bp"][("cu", 2.0)]["zin"]
    np.testing.assert_allclose(z, z_tuned(f), rtol=1e-9)
    f_res, r_in = cmp.cst_resonance((f, z))
    assert abs(f_res - 0.8888e9) < 2e3 and abs(r_in - 0.511) < 1e-9
    rec = cmp.cst_v5bp_resonances(cst)
    eta = cmp.cst_eta_estimate(rec, 2.0)
    assert abs(eta - 0.27 * (0.8888 / 0.8920) ** 4 / 0.511) < 1e-5
    # Rad_efficacity.txt in dB, interpolated in dB
    assert abs(cmp.cst_rad_efficiency_v5bp(cst, 2.0, 0.9e9) - 10 ** (-2.8516808503608 / 10)) < 1e-12
    e = cmp.cst_rad_efficiency_v5bp(cst, 2.0, 0.85e9)
    assert abs(10 * np.log10(e) - 0.5 * (-3.4235155055254 - 2.8516808503608)) < 1e-9


def test_touchstone_r0_needs_reference(fake_tree):
    s1p = next((fake_tree["cst"] / "V5b'").rglob("*.s1p"))
    with pytest.raises(ValueError, match="R 0"):
        cmp.read_touchstone_1port(s1p)
    f, z = cmp.read_touchstone_1port(s1p, r_ref=1.0)
    np.testing.assert_allclose(z, z_tuned(f), rtol=1e-9)


def test_frequency_unit_detection():
    assert cmp.frequency_scale(['#"Frequency / GHz"']) == 1e9
    assert cmp.frequency_scale(["Frequency [MHz]  S11"]) == 1e6
    assert cmp.frequency_scale(["no unit here"], default=1.0) == 1.0


def test_all_figures_written(fake_tree):
    figs = cmp.main(["--cst", str(fake_tree["cst"]), "--mom", str(fake_tree["mom"]),
                     "--fig", str(fake_tree["fig"])])
    names = sorted(Path(f).name for f in figs)
    assert names == sorted(["V5a_zin.png", "V5a_pattern_xy.png", "V5a_mesh_convergence.png",
                            "V5bp_rin_eta_vs_w.png", "V5bp_mesh_convergence.png", "V5bp_zin_w2mm.png",
                            "V5b_zin_w2mm.png", "V5b_eta_vs_w.png", "V5b_mesh_convergence.png"])
    for f in figs:
        assert Path(f).stat().st_size > 10_000
