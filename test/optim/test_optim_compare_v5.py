def z_dipole(f_hz):
    return 70.0 + 0.5j * (f_hz / 1e6 - 900.0)


def z_loop(f_hz, r_loss):
    return (0.9 + r_loss) + 1j * (375.0 + 0.4 * (f_hz / 1e6 - 900.0))


def z_tuned(f_hz, f_res=0.8888e9, r=0.511, L=60e-9):
    """Series RLC resonating at f_res with resistance r (the CST V5b' w = 2 mm values)."""
    w, w0 = 2 * np.pi * f_hz, 2 * np.pi * f_res
    C = 1 / (w0 ** 2 * L)
    return r + 1j * (w * L - 1 / (w * C))


def _s(z, r=50.0):
    return (z - r) / (z + r)


def _write_s1p(path, f_hz, z, unit="GHz", fmt="MA", r_port=50.0, r_written=None):
    s = _s(z, r_port)
    scale = {"GHz": 1e9, "MHz": 1e6}[unit]
    r_written = r_port if r_written is None else r_written
    lines = ["! TOUCHSTONE file generated by CST MICROWAVE STUDIO",
             "! Parameters = {cote=20; w=2}",
             "! S-Parameters are not renormalized. Unphysical impedance of 0 will be written.",
             f"# {unit} S {fmt} R {r_written:g}"]
    for f, x in zip(f_hz, s):
        if fmt == "MA":
            a, b = abs(x), np.degrees(np.angle(x))
        elif fmt == "DB":
            a, b = 20 * np.log10(abs(x)), np.degrees(np.angle(x))
        else:
            a, b = x.real, x.imag
        lines.append(f"{f / scale:<20.12g} {a:.15g} {b:.15g}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


